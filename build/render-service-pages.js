/* One page per service at /services/<slug>, replacing the old pop-up.

   Runs last in the build: the finished /services page (header, footer,
   atmosphere, soundtrack, closing scene and end reveal) is the shell, and
   only <main> changes. It also writes dist/catalog.json - both lists, the
   templates and this shell - which is what WordPress renders the client's
   own services and projects with. */
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.join(__dirname,'..');
const catalog=require('./catalog'),{esc,rootRelative}=catalog;
const lists=catalog.resolve();

const built=fs.readFileSync(path.join(root,'dist/services.html'),'utf8');
const closing=built.match(/<section class="services-closing"[\s\S]*?<\/section>/)[0];
const css=fs.readFileSync(path.join(root,'src/services/detail.css'),'utf8');
const cssRevision=crypto.createHash('sha256').update(css).digest('hex').slice(0,10);

/* The shell, root-relative and with placeholders for what each page sets. */
let shell=built
 .replace(/<main id="main">[\s\S]*?<\/main>/,'<main id="main">{{main}}</main>')
 .replace('<body class="services-page">','<body class="services-page service-detail">')
 .replace(/<title>.*?<\/title>/,'<title>{{pageTitle}}</title>')
 .replace(/(<meta (?:name="description"|property="og:description") content=")[^"]*/g,'$1{{pageDescription}}')
 .replace(/(<meta property="og:title" content=")[^"]*/,'$1{{pageTitle}}')
 .replace('</head>',`<link rel="stylesheet" href="service.css?v=${cssRevision}"></head>`);
shell=rootRelative(shell);
// The closing scene inside <main> is filled in per page, so make it root-relative too.
const closingRel=rootRelative(closing);

const pageTitle=s=>`${s.title} — Services | INU Media`;
const pages=lists.services.map(s=>({
 id:s.id,
 html:catalog.fill(shell,{main:rootRelative(catalog.detailMain(s,lists.services,lists.projects,lists.chapters,closingRel)),pageTitle:esc(pageTitle(s)),pageDescription:esc(s.summary)})
}));
for(const p of pages)if(/\{\{\w+\}\}/.test(p.html))throw Error(`Unresolved field on /services/${p.id}`);

/* What WordPress needs to draw the same pages from the client's lists. */
const templates={...catalog.T};
const payload={
 note:'Generated by build/render-service-pages.js. WordPress (inu-media-workspace, includes/catalog.php) renders the client-edited services and portfolio with these templates.',
 services:lists.services,projects:lists.projects,chapters:lists.chapters,brands:lists.brands,
 templates,detailShell:shell,closing:closingRel
};

for(const dir of ['dist','site']){
 const dest=path.join(root,dir);
 fs.mkdirSync(path.join(dest,'services'),{recursive:true});
 for(const f of fs.readdirSync(path.join(dest,'services')))if(f.endsWith('.html'))fs.unlinkSync(path.join(dest,'services',f));
 for(const p of pages)fs.writeFileSync(path.join(dest,'services',p.id+'.html'),p.html);
 fs.writeFileSync(path.join(dest,'service.css'),css);
 fs.writeFileSync(path.join(dest,'catalog.json'),JSON.stringify(payload));
}
console.log(`Built ${pages.length} service pages (/services/<slug>) and catalog.json for WordPress.`);
